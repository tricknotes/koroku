package compose

import (
	"encoding/json"
	"fmt"
	"strconv"
	"strings"
)

// OverrideParams is the input for the generated override file.
type OverrideParams struct {
	// Project is the normalized configuration of the repository's Compose
	// file alone (without any override).
	Project Project
	// WebService is published on 127.0.0.1:HostPort -> WebPort.
	WebService string
	WebPort    int
	HostPort   int
	// EnvFile is the absolute path of the env file injected into every service.
	EnvFile string
	// DefaultMemory is used when neither the app nor the repository sets a limit.
	DefaultMemory string
	// AppMemory, when set, applies to every service of the app.
	AppMemory string
	// ServiceMemory overrides the limit of individual services.
	ServiceMemory map[string]string
	// Production marks an app whose environment is production: its
	// services are killed last and reserve memory (ARCHITECTURE 6.2).
	Production bool
	// AppReservation and ServiceReservation set the memory reservation of
	// a production app like AppMemory and ServiceMemory set the limit.
	// "" falls back to the default (half the limit), "0" reserves nothing.
	AppReservation     string
	ServiceReservation map[string]string
	// ProjectName and ReleaseTag name the images of built services (see
	// ReleaseImage). When ReleaseTag is empty, image names are left alone.
	ProjectName string
	ReleaseTag  string
}

// OOM score adjustments written for every service (ARCHITECTURE 6.2).
// Production sits above dockerd (-500) and Caddy (-450) so that neither
// is picked before an app, and below koroku itself (0); staging is above
// everything, so that a host-wide OOM kills staging processes first.
const (
	OOMScoreAdjProduction = -400
	OOMScoreAdjStaging    = 500
)

// DefaultReservationPercent is the share of a production service's memory
// limit reserved when the app settings do not say otherwise.
const DefaultReservationPercent = 50

// MinReservation is the smallest reservation Docker accepts.
const MinReservation = 6 << 20

// ReleaseImage is the image name given to a built service for one release.
// Compose would otherwise tag every build as <project>-<service>:latest, so
// a failed release would overwrite the image the previous release runs on
// and a rollback would start the broken image again.
func ReleaseImage(project, service, tag string) string {
	return strings.ToLower(project+"-"+service) + ":" + tag
}

// ReleaseImages lists the images Override assigns to the built services.
func (p OverrideParams) ReleaseImages() []string {
	if p.ReleaseTag == "" {
		return nil
	}
	var images []string
	for _, name := range p.Project.ServiceNames() {
		if p.Project.Services[name].HasBuild() {
			images = append(images, ReleaseImage(p.ProjectName, name, p.ReleaseTag))
		}
	}
	return images
}

// Override renders koroku.override.yaml. The output is deterministic so that it
// can always be regenerated from the database.
//
// For every service it
//   - replaces ports: the web service is published on loopback only
//     (!override), every other service loses its published ports (!reset);
//   - appends the app's env file;
//   - sets restart: unless-stopped unless the repository chose a policy
//     (one-shot services such as migrations declare restart: "no");
//   - applies a memory limit (see memoryLimit), raising memswap_limit with it
//     when the repository's value would end up below the limit;
//   - gives built services a per-release image name (see ReleaseImage);
//   - sets oom_score_adj by the app's environment and, for production, a
//     memory reservation (see Reservations); a staging service loses any
//     reservation the repository set.
func Override(p OverrideParams) ([]byte, error) {
	if _, ok := p.Project.Services[p.WebService]; !ok {
		return nil, fmt.Errorf("web service %q is not defined in the Compose file", p.WebService)
	}
	if p.WebPort < 1 || p.WebPort > 65535 || p.HostPort < 1 || p.HostPort > 65535 {
		return nil, fmt.Errorf("invalid port mapping %d -> %d", p.HostPort, p.WebPort)
	}
	if p.EnvFile == "" {
		return nil, fmt.Errorf("env file path is required")
	}

	var b strings.Builder
	b.WriteString("# Generated by koroku. Do not edit: it is rewritten on every deploy.\n")
	b.WriteString("services:\n")
	for _, name := range p.Project.ServiceNames() {
		svc := p.Project.Services[name]
		fmt.Fprintf(&b, "  %s:\n", quote(name))
		if svc.HasBuild() && p.ReleaseTag != "" {
			fmt.Fprintf(&b, "    image: %s\n", quote(ReleaseImage(p.ProjectName, name, p.ReleaseTag)))
		}
		if name == p.WebService {
			b.WriteString("    ports: !override\n")
			fmt.Fprintf(&b, "      - %s\n", quote(fmt.Sprintf("127.0.0.1:%d:%d", p.HostPort, p.WebPort)))
		} else {
			b.WriteString("    ports: !reset []\n")
		}
		b.WriteString("    env_file:\n")
		fmt.Fprintf(&b, "      - %s\n", quote(p.EnvFile))
		if svc.Restart == "" {
			b.WriteString("    restart: unless-stopped\n")
		}
		limit := p.memoryLimit(name, svc.ownMemoryLimit())
		reservation := p.reservation(name, MemoryShape{OwnLimit: svc.ownMemoryLimit(), OneShot: p.Project.OneShot(name)})
		// Compose rejects a project that sets mem_limit and
		// deploy.resources.limits.memory (or mem_reservation and
		// deploy.resources.reservations.memory) to different values, so
		// each is written in whichever form the repository already uses.
		usesDeploy := svc.DeployMemoryLimit() != "" || svc.DeployMemoryReservation() != ""
		deployLimit := limit != "" && svc.DeployMemoryLimit() != ""
		deployReservation := reservation > 0 && usesDeploy
		resetDeployReservation := reservation == 0 && svc.DeployMemoryReservation() != ""
		if deployLimit || deployReservation || resetDeployReservation {
			b.WriteString("    deploy:\n      resources:\n")
			if deployLimit {
				fmt.Fprintf(&b, "        limits:\n          memory: %s\n", quote(limit))
			}
			if deployReservation {
				fmt.Fprintf(&b, "        reservations:\n          memory: %s\n", quote(formatMemory(reservation)))
			} else if resetDeployReservation {
				b.WriteString("        reservations:\n          memory: !reset null\n")
			}
		}
		if limit != "" {
			if svc.MemLimit != "" || svc.DeployMemoryLimit() == "" {
				fmt.Fprintf(&b, "    mem_limit: %s\n", quote(limit))
			}
			// Docker refuses a memory+swap limit below the memory limit. A
			// repository that set memswap_limit (often equal to its own
			// mem_limit, to forbid swap) would stop starting once the app
			// settings raise the memory limit, so it is raised along.
			if swap, ok := ParseMemory(svc.MemswapLimit); ok {
				if mem, ok := ParseMemory(limit); ok && swap < mem {
					fmt.Fprintf(&b, "    memswap_limit: %s\n", quote(limit))
				}
			}
		}
		// Whatever the repository wrote: a negative value would let any
		// app jump the queue ahead of production.
		adj := OOMScoreAdjStaging
		if p.Production {
			adj = OOMScoreAdjProduction
		}
		fmt.Fprintf(&b, "    oom_score_adj: %d\n", adj)
		switch {
		case reservation > 0 && (svc.MemReservation != "" || !usesDeploy):
			fmt.Fprintf(&b, "    mem_reservation: %s\n", quote(formatMemory(reservation)))
		case reservation == 0 && svc.MemReservation != "":
			b.WriteString("    mem_reservation: !reset null\n")
		}
	}
	return []byte(b.String()), nil
}

// Reservations returns the memory reservation, in bytes, that Override
// gives each service. Services without one are left out, so a staging app
// has none.
func (p OverrideParams) Reservations() map[string]int64 {
	return p.ReservationsFor(p.Project.MemoryShapes())
}

// MemoryShape is what a service's memory limit and reservation depend on
// besides the app settings. A deployment records the shapes of its release
// so that the reservations the current settings would give can be told
// without the Compose file (ARCHITECTURE 6.2).
type MemoryShape struct {
	// OwnLimit is the limit the repository sets, as Compose prints it.
	OwnLimit string `json:"own_limit,omitempty"`
	// OneShot: see Project.OneShot.
	OneShot bool `json:"one_shot,omitempty"`
}

// MemoryShapes returns the memory shape of every service.
func (p Project) MemoryShapes() map[string]MemoryShape {
	out := make(map[string]MemoryShape, len(p.Services))
	for name, svc := range p.Services {
		out[name] = MemoryShape{OwnLimit: svc.ownMemoryLimit(), OneShot: p.OneShot(name)}
	}
	return out
}

// ReservationsFor is Reservations for services of the given shapes; the
// Project of p is not used.
func (p OverrideParams) ReservationsFor(shapes map[string]MemoryShape) map[string]int64 {
	out := map[string]int64{}
	for name, shape := range shapes {
		if r := p.reservation(name, shape); r > 0 {
			out[name] = r
		}
	}
	return out
}

// ownMemoryLimit is the limit the repository sets, in either form.
func (s Service) ownMemoryLimit() string {
	if s.MemLimit != "" {
		return s.MemLimit
	}
	return s.DeployMemoryLimit()
}

// reservation is the memory reservation of a service in bytes, 0 for none.
// Only production apps reserve. Precedence mirrors the limit: per-service
// app setting, app-wide setting, DefaultReservationPercent of the limit.
// The result never exceeds the limit the service ends up with (Docker
// refuses that), and one below MinReservation is dropped. A one-shot
// service (see Project.OneShot) has exited once the app is up, so it
// reserves nothing whatever the settings say.
func (p OverrideParams) reservation(name string, shape MemoryShape) int64 {
	if !p.Production || shape.OneShot {
		return 0
	}
	limit, hasLimit := ParseMemory(p.effectiveLimit(name, shape.OwnLimit))
	value := p.ServiceReservation[name]
	if value == "" {
		value = p.AppReservation
	}
	var r int64
	switch value {
	case "":
		if hasLimit {
			r = limit * DefaultReservationPercent / 100 / (1 << 20) * (1 << 20)
		}
	case "0":
		return 0
	default:
		r, _ = ParseMemory(value)
	}
	if hasLimit && r > limit {
		r = limit
	}
	if r < MinReservation {
		return 0
	}
	return r
}

// effectiveLimit is the memory limit the service runs with: the one the
// override writes, or the repository's own when the override leaves it.
func (p OverrideParams) effectiveLimit(name, own string) string {
	if limit := p.memoryLimit(name, own); limit != "" {
		return limit
	}
	return own
}

// formatMemory renders bytes in MiB when they divide evenly, for a
// readable override, and as plain bytes otherwise.
func formatMemory(bytes int64) string {
	if bytes%(1<<20) == 0 {
		return strconv.FormatInt(bytes>>20, 10) + "m"
	}
	return strconv.FormatInt(bytes, 10)
}

// memoryLimit picks the limit to write for a service, or "" to leave the
// repository's own setting alone. Precedence: per-service app setting,
// app-wide setting, the repository's own limit when it does not exceed the
// configured default, the configured default. The default is a ceiling for
// what a repository can claim on its own: raising a limit is done in the
// app settings, not in the Compose file.
func (p OverrideParams) memoryLimit(name, own string) string {
	if v := p.ServiceMemory[name]; v != "" {
		return v
	}
	if p.AppMemory != "" {
		return p.AppMemory
	}
	if own != "" {
		limit, okLimit := ParseMemory(own)
		ceiling, okCeiling := ParseMemory(p.DefaultMemory)
		if okLimit && okCeiling && limit <= ceiling {
			return ""
		}
	}
	return p.DefaultMemory
}

// ParseMemory converts a Compose memory value ("512m", "1g", "134217728")
// to bytes.
func ParseMemory(value string) (int64, bool) {
	v := strings.ToLower(strings.TrimSpace(value))
	v = strings.TrimSuffix(v, "b")
	if v == "" {
		return 0, false
	}
	multiplier := int64(1)
	switch v[len(v)-1] {
	case 'k':
		multiplier, v = 1<<10, v[:len(v)-1]
	case 'm':
		multiplier, v = 1<<20, v[:len(v)-1]
	case 'g':
		multiplier, v = 1<<30, v[:len(v)-1]
	}
	n, err := strconv.ParseInt(v, 10, 64)
	if err != nil || n <= 0 {
		return 0, false
	}
	return n * multiplier, true
}

// quote renders s as a YAML double-quoted scalar. A JSON string is a valid
// YAML double-quoted scalar, which avoids a YAML dependency for output.
func quote(s string) string {
	b, err := json.Marshal(s)
	if err != nil {
		// Marshaling a string cannot fail.
		panic(err)
	}
	return string(b)
}
