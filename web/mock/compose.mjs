// The Compose tab of the mock (ARCHITECTURE 9.10): the override koroku
// wrote for a release, the merged configuration with values masked, and
// the containers compared with the current release.

const MiB = 1024 * 1024;
const MASKED = '"[MASKED]"';

/** The services of every mock app, with what they build or pull. */
const SERVICES = [
  { name: 'db', image: 'postgres:17', limit: '1g', web: false },
  { name: 'web', build: true, limit: '512m', web: true },
  { name: 'worker', build: true, limit: '512m', web: false },
];

function releaseOf(entry) {
  return entry.source_deployment_id ?? entry.id;
}

/** Kept releases, newest first, as the engine lists them. */
function keptReleases(state, app) {
  const list = state.deployments.get(app.slug) ?? [];
  const byId = new Map(list.map((entry) => [entry.id, entry]));
  const out = [];
  const seen = new Set();
  for (const entry of list) {
    if (entry.status !== 'succeeded' || !entry.rollback_available) continue;
    const id = releaseOf(entry);
    if (seen.has(id)) continue;
    seen.add(id);
    const target = byId.get(id) ?? entry;
    out.push({
      deployment_id: id,
      commit_sha: target.commit_sha,
      commit_message: target.commit_message,
      finished_at: target.finished_at,
      current: id === app.current_deployment?.id,
    });
    if (out.length === 3) break;
  }
  const current = app.current_deployment;
  if (current && !seen.has(current.id)) {
    out.unshift({
      deployment_id: current.id,
      commit_sha: current.commit_sha,
      commit_message: current.commit_message,
      finished_at: current.finished_at,
      current: true,
    });
  }
  return out;
}

function limitOf(app, svc, older) {
  if (older && svc.name === 'web') return '384m';
  return app.service_memory_limits?.[svc.name] || app.memory_limit || svc.limit;
}

function bytesOf(size) {
  const n = Number.parseInt(size, 10);
  return size.endsWith('g') ? n * 1024 * MiB : n * MiB;
}

function reservationOf(app, svc, older) {
  if (app.environment !== 'production') return 0;
  const set = app.service_memory_reservations?.[svc.name];
  if (set === '0') return 0;
  if (set) return bytesOf(set);
  return Math.floor(bytesOf(limitOf(app, svc, older)) / 2 / MiB) * MiB;
}

function megabytes(bytes) {
  return `${bytes / MiB}m`;
}

function overrideOf(app, id, older) {
  const production = app.environment === 'production';
  const env = `/var/lib/koroku/apps/${app.slug}/env`;
  const lines = [
    '# Generated by koroku. Do not edit: it is rewritten on every deploy.',
    'services:',
  ];
  for (const svc of SERVICES) {
    lines.push(`  "${svc.name}":`);
    if (svc.build) {
      lines.push(`    image: "koroku-${app.slug}-${svc.name}:r${id}"`);
    }
    if (svc.web) {
      lines.push(
        '    ports: !override',
        `      - "127.0.0.1:${app.host_port}:${app.web_port}"`,
      );
    } else {
      lines.push('    ports: !reset []');
    }
    lines.push(
      '    env_file:',
      `      - "${env}"`,
      '    restart: unless-stopped',
    );
    lines.push(`    mem_limit: "${limitOf(app, svc, older)}"`);
    lines.push(`    oom_score_adj: ${production ? -400 : 500}`);
    const reserved = reservationOf(app, svc, older);
    if (!production) {
      lines.push('    mem_reservation: !reset null');
    } else if (reserved > 0) {
      lines.push(`    mem_reservation: "${megabytes(reserved)}"`);
    }
  }
  return lines.join('\n') + '\n';
}

function configOf(app, id, older) {
  const production = app.environment === 'production';
  const env = `/var/lib/koroku/apps/${app.slug}/env`;
  const release = `/var/lib/koroku/apps/${app.slug}/releases/${id}`;
  const lines = [`name: koroku-${app.slug}`, 'networks:', '  default:'];
  lines.push(`    name: koroku-${app.slug}_default`, 'services:');
  for (const svc of SERVICES) {
    lines.push(`  ${svc.name}:`);
    if (svc.build) {
      lines.push(
        '    build:',
        '      args:',
        `        BUNDLE_WITHOUT: ${MASKED}`,
        `      context: ${release}`,
        '      dockerfile: Dockerfile',
      );
    }
    if (svc.name === 'worker') {
      lines.push('    command:', '      - bin/jobs');
    }
    if (svc.name !== 'db') {
      lines.push(
        '    depends_on:',
        '      db:',
        '        condition: service_healthy',
        '        required: true',
      );
    }
    lines.push(
      '    env_file:',
      `      - path: ${env}`,
      '        required: true',
      '    environment:',
    );
    if (svc.name === 'db') {
      lines.push(
        `      POSTGRES_PASSWORD: ${MASKED}`,
        `      POSTGRES_USER: ${MASKED}`,
      );
    } else {
      lines.push(`      DATABASE_URL: ${MASKED}`, `      RAILS_ENV: ${MASKED}`);
    }
    if (svc.name === 'db') {
      lines.push(
        '    healthcheck:',
        '      test:',
        '        - CMD',
        '        - pg_isready',
        '        - "-U"',
        '        - "${POSTGRES_USER}"',
      );
    }
    lines.push(
      `    image: ${svc.image ?? `koroku-${app.slug}-${svc.name}:r${id}`}`,
    );
    lines.push(`    mem_limit: ${limitOf(app, svc, older)}`);
    const reserved = reservationOf(app, svc, older);
    if (reserved > 0) lines.push(`    mem_reservation: ${megabytes(reserved)}`);
    lines.push(
      '    networks:',
      '      default: null',
      `    oom_score_adj: ${production ? -400 : 500}`,
    );
    if (svc.web) {
      lines.push(
        '    ports:',
        '      - host_ip: "127.0.0.1"',
        '        mode: ingress',
        '        protocol: tcp',
        `        published: "${app.host_port}"`,
        `        target: ${app.web_port}`,
      );
    } else {
      lines.push('    ports: []');
    }
    lines.push('    restart: unless-stopped');
    if (svc.name === 'db') {
      lines.push(
        '    volumes:',
        '      - source: pgdata',
        '        target: /var/lib/postgresql/data',
        '        type: volume',
      );
    }
  }
  lines.push('volumes:', '  pgdata:', `    name: koroku-${app.slug}_pgdata`);
  return lines.join('\n') + '\n';
}

/**
 * GET /api/apps/:slug/compose. Returns [status, body], the body being an
 * error code for a status other than 200.
 */
export function composeView(state, app, deployment, scenario) {
  const current = app.current_deployment;
  if (!current) return [409, 'not_deployed'];
  const releases = keptReleases(state, app);
  const id = deployment ? Number(deployment) : current.id;
  if (!releases.some((r) => r.deployment_id === id)) {
    return [409, 'release_unavailable'];
  }
  const older = id !== current.id;
  const broken = scenario === 'compose-mismatch' && older;
  return [
    200,
    {
      deployment_id: id,
      current_deployment_id: current.id,
      releases,
      compose_file: 'compose.yaml',
      files: ['compose.yaml', 'koroku.override.yaml'],
      override: overrideOf(app, id, older),
      config: broken ? null : configOf(app, id, older),
      config_error: broken
        ? 'docker compose config: docker: exit status 15: service "worker" refers to undefined volume uploads: invalid compose project'
        : '',
    },
  ];
}

/** 64 hex digits that stay the same for a name. */
function hex(name) {
  let value = [...name].reduce((sum, c) => sum * 31 + c.charCodeAt(0), 7);
  let out = '';
  while (out.length < 64) {
    value = (value * 48271) % 2147483647;
    out += (value % 16).toString(16);
  }
  return out;
}

function ago(ms) {
  return new Date(Date.now() - ms).toISOString();
}

/** GET /api/apps/:slug/containers. */
export function containerView(state, app, scenario) {
  const current = app.current_deployment;
  if (!current) {
    return {
      current_deployment_id: null,
      compared: false,
      comparison_error: '',
      containers: [],
    };
  }
  const stopped = app.desired_state === 'stopped';
  const production = app.environment === 'production';
  const troubled = scenario === 'compose-mismatch' && app.slug === 'blog';
  const list = state.deployments.get(app.slug) ?? [];
  const previous = list.find(
    (entry) => entry.status === 'succeeded' && releaseOf(entry) !== current.id,
  );
  const created = current.finished_at;
  const containers = SERVICES.map((svc) => {
    const limit = bytesOf(limitOf(app, svc, false));
    const reserved = reservationOf(app, svc, false);
    const expected = {
      memory_limit_bytes: limit,
      memory_reservation_bytes: reserved,
      oom_score_adj: production ? -400 : 500,
    };
    const info = {
      name: `koroku-${app.slug}-${svc.name}-1`,
      service: svc.name,
      image: svc.image ?? `koroku-${app.slug}-${svc.name}:r${current.id}`,
      image_id: `sha256:${hex(svc.name)}`,
      image_digest: svc.image
        ? 'postgres@sha256:6f1a2b3c4d5e6f7a8b9c0d1e2f3a4b5c6d7e8f9a0b1c2d3e4f5a6b7c8d9e0f1a'
        : null,
      created_at: created,
      deployment_id: current.id,
      matched_by: svc.build ? 'image' : 'created_at',
      current: true,
      state: stopped ? 'exited' : 'running',
      health: !stopped && svc.name !== 'worker' ? 'healthy' : '',
      exit_code: 0,
      started_at: created,
      finished_at: stopped ? ago(2 * 60 * 60 * 1000) : null,
      restart_count: 0,
      oom_killed: false,
      memory_limit_bytes: limit,
      memory_reservation_bytes: reserved,
      oom_score_adj: expected.oom_score_adj,
      expected,
      ports:
        svc.web && !stopped
          ? [
              {
                host_ip: '127.0.0.1',
                host_port: String(app.host_port),
                container_port: `${app.web_port}/tcp`,
              },
            ]
          : [],
      mismatches: [],
    };
    if (!troubled) return info;
    if (svc.name === 'web') {
      // Killed by its limit and restarted by Docker.
      return {
        ...info,
        oom_killed: true,
        restart_count: 3,
        started_at: ago(4 * 60 * 1000),
        mismatches: ['oom_killed', 'restarted'],
      };
    }
    if (svc.name === 'worker' && previous) {
      // Left over from the release before, with that release's limit.
      return {
        ...info,
        image: `koroku-${app.slug}-worker:r${releaseOf(previous)}`,
        created_at: previous.finished_at,
        started_at: previous.finished_at,
        deployment_id: releaseOf(previous),
        matched_by: 'image',
        current: false,
        memory_limit_bytes: 384 * MiB,
        memory_reservation_bytes: 192 * MiB,
        mismatches: ['outdated', 'memory_limit', 'memory_reservation'],
      };
    }
    if (svc.name === 'db') {
      // Restarting after an error, with an adjusted OOM score.
      return {
        ...info,
        state: 'restarting',
        health: 'unhealthy',
        exit_code: 1,
        restart_count: 12,
        oom_score_adj: 0,
        mismatches: ['oom_score_adj', 'restarting', 'restarted', 'unhealthy'],
      };
    }
    return info;
  });
  return {
    current_deployment_id: current.id,
    compared: true,
    comparison_error: '',
    containers,
  };
}
